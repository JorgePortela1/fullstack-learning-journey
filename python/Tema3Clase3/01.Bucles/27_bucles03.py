# ---- PROGRAMA QUE TRAS UNA PALABRA POR EL USUARIO, SE IMPRIMA UNA A UNA LAS LETRAS DESDE EL FINAL HACIA EL PRINCIPIO

# CREAMOS LA VARIABLE QUE ALMACENE LA PALABRA INTRODUCIDA POR EL USUARIO
wrd = input("Introduce una palabra: ")

# CREAMOS LA VARIABLE QUE INDIQUE EL NUMERO DE LETRAS QUE TIENE LA PALABRA
longitud = len(wrd)

# CON UN BUCLE RECORREMOS LA PALABRA
## ([inicio],[fin],[salto])
for i in range(longitud-1, -1, -1):
	print(wrd[i])

